    <h1 class="page-access__heading page-heading"><span>ソーシャルメディアポリシー</span></h1>
    <div class="page-policy__intro">
      <p>学校法人岩崎学園 （以下、本学園）は、ソーシャルメディア公式アカウントを利用し、情報を発信する際の方針を下記の通り定め、これを遵守します。<br>本メディアポリシーは、本学園が公式に運営している、各ソーシャルメディアアカウントに適用されます。</p>
    </div>
    <div class="page-policy__main">
      <h3>1.メディアポリシー</h3>
      <ul class="no-padding">
        <li>・法令等に違反するもの、公序良俗に反する内容を投稿しません。</li>
        <li>・個人情報を含む内容、名誉、著作権、肖像権など、個人の権利や人権を侵害する内容を投稿しません。</li>
        <li>・関係者および本学園の機密情報を、許可なく公開しません。</li>
        <li>・違法性のあるコンテンツや、誹謗・中傷、差別的表現を含む内容を投稿しません。</li>
        <li>・虚偽または著しく事実と異なる内容を投稿しません。</li>
        <li>・本学園外のアカウントの発言・投稿に対する返信・コメント・リツイート・リポスト等は、原則行いません。</li>
        <li>・発信した情報は、予告なく後日訂正する場合があります。</li>
        <li>・本メディアポリシーの内容は、予告なく適宜変更する場合があります。</li>
      </ul>
    </div>
